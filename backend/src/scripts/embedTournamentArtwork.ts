import fs from "node:fs";
import path from "node:path";

// Keep the standalone templates portable: embed the project assets, never external URLs.
const root = path.resolve(__dirname, "../../..");
const assets = path.join(root, "design/diplomas/code-form/assets");
const entries = ([0, 1, 2, 3] as const).map(rank => {
  const filename = rank === 0 ? "spiral-participant" : `spiral-place-${rank}`;
  const source = fs.readFileSync(path.join(assets, `${filename}.png`));
  const width = source.readUInt32BE(16);
  const height = source.readUInt32BE(20);
  const encoded = fs.readFileSync(path.join(assets, `${filename}.webp`));
  return `  ${rank}: ${JSON.stringify({
    dataUrl: `data:image/webp;base64,${encoded.toString("base64")}`,
    width, height, viewBox: `0 0 ${width} ${height}`,
  })},`;
});
fs.writeFileSync(path.join(root, "shared/tournamentSpiralImages.ts"),
  "/** Generated by backend/src/scripts/embedTournamentArtwork.ts from project artwork. */\n" +
  "export const tournamentSpiralImages: Record<0 | 1 | 2 | 3, { dataUrl: string; width: number; height: number; viewBox: string }> = {\n" +
  entries.join("\n") + "\n};\n");
console.log("Embedded all four diploma illustrations.");
